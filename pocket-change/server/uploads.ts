import fs from 'node:fs'
import path from 'node:path'
import type { UploadType } from '../shared/types.ts'

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])

/** Identifies an upload from its first bytes, so a renamed file can't smuggle in another type. */
export function sniffUploadType(bytes: Uint8Array): UploadType | null {
  const buffer = Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  if (buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    return 'image/jpeg'
  }
  if (buffer.subarray(0, 8).equals(PNG_SIGNATURE)) return 'image/png'
  if (
    buffer.subarray(0, 4).toString('latin1') === 'RIFF' &&
    buffer.subarray(8, 12).toString('latin1') === 'WEBP'
  ) {
    return 'image/webp'
  }
  if (buffer.subarray(0, 5).toString('latin1') === '%PDF-') return 'application/pdf'
  return null
}

export function createUploadFolder(directory: string) {
  fs.mkdirSync(directory, { recursive: true })
  // Upload ids are UUIDs generated by the store, but never trust a path segment.
  const fileFor = (id: string) => {
    if (!/^[0-9a-f-]{36}$/.test(id)) throw new Error(`Invalid upload id: ${id}`)
    return path.join(directory, id)
  }

  return {
    write(id: string, bytes: Uint8Array) {
      fs.writeFileSync(fileFor(id), bytes)
    },
    read(id: string): Buffer | null {
      try {
        return fs.readFileSync(fileFor(id))
      } catch {
        return null
      }
    },
    remove(id: string) {
      fs.rmSync(fileFor(id), { force: true })
    },
  }
}

export type UploadFolder = ReturnType<typeof createUploadFolder>
